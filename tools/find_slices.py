"""
find_slices.py -- where each game table is in the ROM.

Reads a dump of the tables (build/ff1-dump-ref) and the ROM, and writes
src/rom_layout.h: for every table whose bytes are one run of the ROM, where
(SLICE(name, offset), an offset in the 256 KB).  src/romdata.c copies those;
the tables listed as not found are built by its own code.

    python tools/find_slices.py <dump> [rom]

The layout holds offsets only -- no data.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.dirname(HERE)


def tables(path):
    lines = open(path, encoding="utf-8").read().splitlines()
    i = 0
    while i < len(lines):
        head = lines[i].split()
        if len(head) == 3 and head[2] == "strings":
            yield head[0], None
            i += 1 + int(head[1])
        else:
            yield head[0], bytes.fromhex(lines[i + 1])
            i += 2


def main():
    dump = sys.argv[1]
    rom_path = sys.argv[2] if len(sys.argv) > 2 else os.environ.get("FF1_ROM") or \
        os.path.join(os.path.dirname(PORT), "FinalFantasy.nes")
    rom = open(rom_path, "rb").read()
    if len(rom) == 0x40010:
        rom = rom[16:]
    found, missing = [], []
    for name, data in tables(dump):
        off = rom.find(data) if data else -1
        if data and off >= 0:
            found.append((name, off))
        else:
            missing.append((name, len(data) if data else None))
    with open(os.path.join(PORT, "src", "rom_layout.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/find_slices.py: where the game's tables that are\n"
                " * one run of the ROM are (offsets in its 256 KB).  No data. */\n\n")
        for name, off in found:
            f.write(f"SLICE({name}, 0x{off:05X})   /* bank {off // 0x4000:02X} +{off % 0x4000:04X} */\n")
    print(f"{len(found)} tables are ROM slices; {len(missing)} need code:")
    for name, n in missing:
        print(f"  {name} ({'strings' if n is None else n})")


if __name__ == "__main__":
    main()
